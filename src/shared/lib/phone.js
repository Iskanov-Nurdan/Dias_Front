/**
 * Телефон для показа на экране: «+996776223223» → «+996 776 223 223».
 *
 * Форматирование только для вывода — в базе номер остаётся как есть.
 * Хранить «красивую» строку с пробелами нельзя: по ней ломается сравнение
 * дубликатов и ссылки на WhatsApp, которые собираются из одних цифр.
 *
 * Правило намеренно осторожное: разбивается только то, что уверенно
 * опознаётся как номер. В базе лежат сотни обрезанных записей (по 5-8 цифр,
 * с опечатками), и дорисовывать им «+996» нельзя — сотрудник увидел бы
 * аккуратный номер вместо явно сломанного и звонил бы впустую. Всё, что не
 * опознано, возвращается ровно в том виде, в каком лежит.
 */
const groupBy3 = (digits) => digits.replace(/(\d{3})(?=\d)/g, '$1 ');

export const formatPhoneDisplay = (raw) => {
  const value = String(raw ?? '').trim();
  if (!value) return '';

  const digits = value.replace(/\D/g, '');

  // +996 700 123 456 — канонический вид, в котором сохраняются новые заявки
  if (digits.length === 12 && digits.startsWith('996')) {
    return `+996 ${groupBy3(digits.slice(3))}`;
  }
  // 0700 123 456 — местная запись, оставляем местной: приписывать код страны
  // значит утверждать то, чего в данных нет
  if (digits.length === 10 && digits.startsWith('0')) {
    return `0${groupBy3(digits.slice(1))}`;
  }
  // 700 123 456 — номер без кода, таких в базе больше всего
  if (digits.length === 9) {
    return groupBy3(digits);
  }

  return value;
};
